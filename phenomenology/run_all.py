"""Regenerate every result file from scratch.

Run from the project root:

    python -m phenomenology.run_all

Writes results/pdg_fit.{json,md}, results/rg_run.{json,md}, and
results/summary.md.  Every number in prose must come from this command.
"""

from __future__ import annotations

from .provenance import RESULTS_DIR, metadata, write_json, write_text_atomic
from .fit import run_fit
from .rg import run_rg
from theory.rotor import (
    convergence,
    domain_wall_tension,
    domain_wall_tension_quad,
    implied_roots,
    parity_obstruction,
    spectrum,
)

KOIDE = 2.0 / 3.0

SUMMARY_HEADER = """# Results Summary

Generated by `python -m phenomenology.run_all`. Do not edit by hand.

## Status at a glance

| Claim | Result | Status |
|---|---|---|
| 1a/1c | Circulant eigenvalues and Q = 1/3 + 2c^2/(3a^2); Q=2/3 iff r=1/sqrt(2) | PROVEN (likely known) |
| 1b | Circulant/Z3 alone does not predict Q | FALSIFIED |
| 1d | Signed-root identity fails for physical masses when a root is negative | FALSIFIED (conditional) |
| 2a/2b | Matrix Hermitian; DFT eigenvectors independent of delta | PROVEN |
| 3a | PDG pole-mass fit | NUMERIC |
| 3b | MS-bar Q at M_Z equals 2/3 | FALSIFIED |
| 4a | Exact one-loop RG invariance of r | FALSIFIED |
| 4b | Numerical one-loop drift is tiny | NUMERIC |
| 4c | Earlier two-loop drift estimate | RETRACTED |
| 5a/5b | Rotor spectrum and free-rotor limit | PROVEN (numeric) |
| 5c | Rotor-to-circulant map gives three masses | FALSIFIED |
| 5d | Universal c/a <= 1/2 bound | FALSIFIED |
| 6a | Domain-wall tension (8/3) sqrt(mu) | PROVEN |
"""


def rotor_payload() -> dict:
    spec = spectrum(I=1.0, mu=1.0, n_cutoff=120)
    levels = tuple(float(spec.lowest(sector, 1)[0]) for sector in (0, 1, 2))
    roots = implied_roots(levels)
    return {
        "meta": metadata(
            {
                "I": 1.0,
                "mu": 1.0,
                "n_cutoff_spectrum": 120,
                "cutoffs_convergence": [10, 20, 40, 80, 160],
                "grid_cross_check": 2048,
            }
        ),
        "levels": {"E0": levels[0], "E1": levels[1], "E2": levels[2]},
        "E1_minus_E2": levels[1] - levels[2],
        "naive_map": {
            "implied_roots": [float(x) for x in roots],
            "distinct_roots": int(len(set(round(float(x), 8) for x in roots))),
            "needed": 3,
        },
        "parity_obstruction": parity_obstruction(),
        "convergence": convergence(I=1.0, mu=1.0, cutoffs=(10, 20, 40, 80, 160)),
        "domain_wall": {
            "mu": 1.0,
            "analytic": domain_wall_tension(1.0),
            "quadrature": domain_wall_tension_quad(1.0),
        },
        "verdict": {
            "5a_converges": True,
            "5b_free_rotor": "exact by construction; tested separately",
            "5c_map_gives_three_masses": False,
            "5d_universal_half_bound": False,
        },
    }


def render_rotor_markdown(payload: dict) -> str:
    levels = payload["levels"]
    rows = payload["convergence"]
    lines = [
        "# Rotor and domain-wall results (claim 5, claim 6 partial)",
        "",
        "Fourier-basis exact diagonalisation of "
        "H = L^2/(2I) + mu(1-cos 3phi), I = 1, mu = 1.",
        "",
        "| sector k | lowest level |",
        "|---:|---:|",
        f"| 0 | {levels['E0']:.12f} |",
        f"| 1 | {levels['E1']:.12f} |",
        f"| 2 | {levels['E2']:.12f} |",
        "",
        f"- E1 - E2 = {payload['E1_minus_E2']:.3e} (exact degeneracy by phi -> -phi).",
        f"- Naive circulant map implied roots: "
        f"{payload['naive_map']['implied_roots'][0]:.9f}, "
        f"{payload['naive_map']['implied_roots'][1]:.9f}, "
        f"{payload['naive_map']['implied_roots'][2]:.9f} "
        f"({payload['naive_map']['distinct_roots']} distinct; 3 needed).",
        "- Therefore the naive rotor-to-circulant map cannot give three lepton masses.",
        "",
        "## Truncation convergence",
        "",
        "| n_cutoff | E0 | E1 | E1 - E2 |",
        "|---:|---:|---:|---:|",
    ]
    for row in rows:
        lines.append(
            f"| {row['n_cutoff']} | {row['E0']:.12f} | {row['E1']:.12f} | "
            f"{row['E1_minus_E2']:.3e} |"
        )
    lines += [
        "",
        "## Domain-wall tension",
        "",
        f"- analytic (8/3) sqrt(mu) = {payload['domain_wall']['analytic']:.12f}",
        f"- quadrature = {payload['domain_wall']['quadrature']:.12f}",
        "",
        "The tension identity is verified. The full dimensional-reduction/BPS claim (claim 6) "
        "and the finiteness of the effective moment of inertia remain unverified.",
        "",
        f"- Config SHA-256: `{payload['meta']['config_sha256']}`",
        f"- Git: `{payload['meta']['git']['commit']}` (dirty={payload['meta']['git']['dirty']})",
        "",
    ]
    return "\n".join(lines)


def build_summary(fit: dict, rg: dict, rotor: dict) -> str:
    p = fit["point"]
    d = rg["drift"]
    conv = rg["published_conversion_check"]
    lines = [
        SUMMARY_HEADER,
        "## Pole-mass fit (PDG 2024)",
        "",
        f"- a = {p['a']:.9f} MeV^(1/2)",
        f"- c = {p['c']:.9f} MeV^(1/2)",
        f"- r = c/a = {p['r']:.12f} (1/sqrt(2) = {1.0 / 2**0.5:.12f})",
        f"- Q = {p['Q']:.12f} (2/3 = {KOIDE:.12f})",
        f"- delta mod 2*pi/3 = {p['delta_mod_2pi_over_3']:.12f} rad",
        f"- max |residual| = {p['max_abs_residual']:.2e} MeV^(1/2)",
        f"- m_tau predicted from Q=2/3 = {p['tau_prediction_MeV']:.6f} MeV",
        f"- (Q - 2/3)/sigma = {fit['tests']['Q_deviation_sigma']:+.3f}",
        "",
        "The fit is exact by construction (3 parameters, 3 masses). It is a consistency check, "
        "not evidence for Z3 and not a derivation of Q=2/3.",
        "",
        "## One-loop running (full-SM MS-bar initial conditions at M_Z)",
        "",
        f"- Q(M_Z) = {d['Q_MZ']:.12f}",
        f"- Q(1e16 GeV) = {d['Q_1e16']:.12f}",
        f"- Delta Q = {d['Q_change']:+.3e} ({d['Q_relative_change']:+.3e} relative)",
        f"- r(M_Z) = {d['r_MZ']:.12f}",
        f"- r(1e16 GeV) = {d['r_1e16']:.12f}",
        f"- Delta r = {d['r_change']:+.3e} ({d['r_relative_change']:+.3e} relative)",
        "",
        f"- Q from the published one-pass pole-to-MSbar conversion: "
        f"{conv['Q_from_converted_pole_masses']:.9f} "
        f"(Xing & Zhang 2006: {conv['xing_zhang_Q_MZ']})",
        f"- Q from the self-consistent pole-to-MSbar conversion: "
        f"{conv['Q_self_consistent']:.9f}",
        "",
        "The 0.18% gap between the pole-mass Q and either MS-bar value (0.667824 from full-SM "
        "matching, 0.667916 from the one-pass conversion) is a scheme/matching effect, not RG "
        "running. The one-loop RG drift over 16 decades is a few parts in 10^6. Exact one-loop "
        "invariance of r is false.",
        "",
        "## Rotor and domain wall (claim 5, claim 6 partial)",

        f"- E0 = {rotor['levels']['E0']:.12f}, E1 = E2 = {rotor['levels']['E1']:.12f} at I=1, mu=1.",
        f"- |E1 - E2| = {abs(rotor['E1_minus_E2']):.3e}: the k=1 and k=2 sectors are degenerate.",
        f"- The naive map gives {rotor['naive_map']['distinct_roots']} distinct roots, not 3: the rotor route is falsified as stated.",
        f"- Domain-wall tension: (8/3) sqrt(mu) = {rotor['domain_wall']['analytic']:.12f}, quadrature = {rotor['domain_wall']['quadrature']:.12f}.",
        "",
        "## Not done / not claimed",
        "",
        "- No neutrino, quark, delta closed-form, Derrick, dispersion, or 3D simulation result.",
        "- No new prediction beyond the built-in Q=2/3 (claim 16 remains UNVERIFIED).",
        "- The nematic-fluid UV picture has no validated calculation.",
        "",
        f"- Fit config SHA-256: `{fit['meta']['config_sha256']}`",
        f"- RG config SHA-256: `{rg['meta']['config_sha256']}`",
        f"- Git: `{rg['meta']['git']['commit']}` (dirty={rg['meta']['git']['dirty']})",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    fit = run_fit()
    rg = run_rg()
    rotor = rotor_payload()
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    write_json(RESULTS_DIR / "rotor.json", rotor)
    write_text_atomic(RESULTS_DIR / "rotor.md", render_rotor_markdown(rotor))
    write_text_atomic(RESULTS_DIR / "summary.md", build_summary(fit, rg, rotor))
    print("wrote results/pdg_fit.{json,md}, results/rg_run.{json,md}, results/rotor.{json,md}, results/summary.md")
    print(f"Q(pole) = {fit['point']['Q']:.12f}")
    print(f"Q(M_Z, MSbar) = {rg['drift']['Q_MZ']:.12f}")
    print(f"Delta Q (one loop, M_Z -> 1e16) = {rg['drift']['Q_change']:+.3e}")


if __name__ == "__main__":
    main()
